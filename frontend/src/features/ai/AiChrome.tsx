/**
 * A single citation rendered as an inspectable source pill; the two kinds look and behave
 * differently (design §9.1). A **fact** pill jumps to the owning widget and highlights the field —
 * so it shows a readable field name and a "go to" arrow, not a web-link glyph. A **knowledge** pill
 * opens the source passage. Both are buttons; the arrow/label make the interactivity obvious.
 */
export function CitationChip({ citation }: { readonly citation: Citation }): React.JSX.Element {
  const { inspectFact, inspectPassage } = useCitations();
  if (citation.kind === 'fact') {
    return (
      <button
        type="button"
        className="citation citation--fact"
        onClick={() => {
          inspectFact(citation);
        }}
        title={`Go to ${humanizeField(citation.field)} in the ${citation.entity_type} card`}
      >
        <span className="citation__icon" aria-hidden="true">
          ◎
        </span>
        <span className="citation__text">{humanizeField(citation.field)}</span>
        <span className="citation__go" aria-hidden="true">
          ↗
        </span>
      </button>
    );
  }
  return (
    <button
      type="button"
      className="citation citation--passage"
      onClick={() => {
        inspectPassage(citation);
      }}
      title={`Open source: ${citation.title} · ${citation.section_path}`}
    >
      <span className="citation__icon" aria-hidden="true">
        📄
      </span>
      <span className="citation__text">{citation.title}</span>
      <span className="citation__go" aria-hidden="true">
        ↗
      </span>
    </button>
  );
}

/**
 * The two citation lists for a card, kept apart and labelled: facts first, then knowledge. Empty
 * lists render nothing; unavailable inputs are surfaced explicitly beneath them.
 */
export function CitationList({
  facts,
  passages,
  unavailableInputs = [],
}: {
  readonly facts: readonly FactCitation[];
  readonly passages: readonly PassageCitation[];
  readonly unavailableInputs?: readonly string[];
}): React.JSX.Element | null {
  const uniqueFacts = dedupeFacts(facts);
  const hasFacts = uniqueFacts.length > 0;
  const hasPassages = passages.length > 0;
  const hasUnavailable = unavailableInputs.length > 0;
  if (!hasFacts && !hasPassages && !hasUnavailable) {
    return null;
  }
  return (
    <div className="citations">
      {hasFacts && (
        <div className="citations__group">
          <span className="citations__label">
            <span className="citations__label-icon" aria-hidden="true">
              📌
            </span>
            <span className="citations__label-text">Facts</span>
            <span className="citations__count">{uniqueFacts.length}</span>
            <span className="citations__hint">click to jump to the card</span>
          </span>
          <CitationPills citations={uniqueFacts} />
        </div>
      )}
      {hasPassages && (
        <div className="citations__group">
          <span className="citations__label">
            <span className="citations__label-icon" aria-hidden="true">
              📚
            </span>
            <span className="citations__label-text">Knowledge</span>
            <span className="citations__count">{passages.length}</span>
            <span className="citations__hint">click to open the passage</span>
          </span>
          <CitationPills citations={passages} />
        </div>
      )}
      {hasUnavailable && (
        <p className="citations__unavailable">
          Some inputs were unavailable: {unavailableInputs.join(', ')}.
        </p>
      )}
    </div>
  );
}
