import { useState } from 'react';

import type { AgentCard, Citation, FactCitation, PassageCitation } from './types';
import { useCitations } from './CitationContext';

/** Turn a raw field path (`net_worth_cents`) into a readable label ("Net worth"). */
function humanizeField(field: string): string {
  const base = field
    .replace(/_(cents|bps)$/i, '')
    .replace(/_/g, ' ')
    .trim();
  return base.charAt(0).toUpperCase() + base.slice(1);
}

/**
 * Deduplicate fact citations by the field they point at, keeping the first occurrence. Agents often
 * cite the same field many times (e.g. "Expected value" per offer, repeated "Total"s), which floods
 * the list with identical pills; one pill per distinct field carries the same jump targets without
 * the repetition. No information is lost — the first citation for a field resolves to that field's
 * card, which is all a duplicate pill would do.
 */
function dedupeFacts(facts: readonly FactCitation[]): readonly FactCitation[] {
  const seen = new Set<string>();
  const out: FactCitation[] = [];
  for (const fact of facts) {
    const key = `${fact.entity_type}.${fact.field}`;
    if (seen.has(key)) {
      continue;
    }
    seen.add(key);
    out.push(fact);
  }
  return out;
}

/** How many citation pills to show before collapsing the rest behind "See more". */
const CITATION_PREVIEW = 6;

/** A collapsible list of citation pills: shows the first few, with a "See more" for the rest. */
function CitationPills({
  citations,
}: {
  readonly citations: readonly Citation[];
}): React.JSX.Element {
  const [expanded, setExpanded] = useState(false);
  const isLong = citations.length > CITATION_PREVIEW;
  const visible = expanded || !isLong ? citations : citations.slice(0, CITATION_PREVIEW);
  return (
    <>
      <ul className="citations__list">
        {visible.map((citation) => (
          <li key={citation.kind === 'fact' ? citation.fact_id : citation.passage_id}>
            <CitationChip citation={citation} />
          </li>
        ))}
      </ul>
      {isLong && (
        <button
          type="button"
          className="citations__more focus-ring"
          aria-expanded={expanded}
          onClick={() => {
            setExpanded((v) => !v);
          }}
        >
          {expanded ? 'See less' : `See ${citations.length - CITATION_PREVIEW} more`}
        </button>
      )}
    </>
  );
}

/**
 * The shared chrome every AI surface wears (tasks 14.1, 14.2, 14.4).
 *
 * Two obligations run through the whole AI layer and are met here once:
 *
 * - **Honest labelling.** Anything a model produced is labelled as AI-generated, stamped with the
 *   time it was generated, marked when it came from cache, and — when the model was unavailable and
 *   a deterministic template stood in — badged as degraded (requirements 10.1, 10.12). {@link AiMeta}
 *   renders that strip from an {@link AgentCard}'s metadata.
 * - **Traceable claims.** Every figure or piece of guidance in a narrative resolves to a citation.
 *   {@link CitationList} renders the two kinds distinctly (design §9.1): a fact chip opens the owning
 *   widget and highlights the field; a knowledge chip opens the passage viewer. Unavailable inputs
 *   are stated plainly rather than hidden, so a card never implies completeness it does not have
 *   (requirement 10.9).
 */

// ---------------------------------------------------------------- labels and badges

/** The "AI-generated" label every model surface carries (requirement 10.1). */
export function AiLabel(): React.JSX.Element {
  return (
    <span className="ai-label" title="Generated by an AI model">
      <span aria-hidden="true">✦</span> AI-generated
    </span>
  );
}

/** The degraded badge shown when a card fell back to a deterministic template (requirement 10.12). */
export function DegradedBadge(): React.JSX.Element {
  return (
    <span
      className="badge badge--degraded"
      title="The AI model was unavailable; this is a deterministic fallback."
    >
      Degraded
    </span>
  );
}

/** The metadata strip: AI label, generation time, cache indicator and degraded badge. */
export function AiMeta({ card }: { readonly card: AgentCard }): React.JSX.Element {
  return (
    <div className="ai-meta">
      <AiLabel />
      {card.degraded && <DegradedBadge />}
      {card.cache_hit && (
        <span className="badge badge--cache" title="Served from cache">
          Cached
        </span>
      )}
      <time className="ai-meta__time" dateTime={card.generated_at}>
        {formatGeneratedAt(card.generated_at)}
      </time>
      {card.confidence !== null && (
        <span className="ai-meta__confidence">Confidence {Math.round(card.confidence * 100)}%</span>
      )}
    </div>
  );
}

function formatGeneratedAt(iso: string): string {
  const parsed = new Date(iso);
  if (Number.isNaN(parsed.getTime())) {
    return iso;
  }
  return `Generated ${parsed.toLocaleString('en-US', {
    month: 'short',
    day: 'numeric',
    hour: 'numeric',
    minute: '2-digit',
  })}`;
}

